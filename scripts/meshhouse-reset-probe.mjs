import { chromium } from '@playwright/test';
const browser = await chromium.launch({ channel: 'chromium' });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message.slice(0, 160)));
await page.goto('http://127.0.0.1:5188/?godmode=1', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => !document.querySelector('#start-button')?.disabled, null, { timeout: 120_000 });
await page.evaluate(() => document.querySelector('#start-button')?.click());
await page.waitForFunction(() => (window.__THREE_GAME_DIAGNOSTICS__?.frame ?? 0) > 90, null, { timeout: 40_000 });
await page.evaluate(() => window.__THREE_GAME_TEST_HOOKS__?.setState('night'));
await page.waitForTimeout(1000);
const houses = await page.evaluate(() => window.__THREE_GAME_TEST_HOOKS__?.yardHouses());
await page.evaluate(({ x, z }) => window.__THREE_GAME_TEST_HOOKS__?.chewHouseAt(x, z, 1.5, 2), { x: houses[0].x, z: houses[0].z });
await page.evaluate(({ x, z }) => window.__THREE_GAME_TEST_HOOKS__?.collapseHouseAt(x, z), { x: houses[1].x, z: houses[1].z });
await page.waitForTimeout(400);
const wrecked = await page.evaluate(() => window.__THREE_GAME_TEST_HOOKS__?.meshHouseInfo());
console.log('[wrecked] h0 fraction:', wrecked.houses[0].fraction, 'h1 collapsed:', wrecked.houses[1].collapsed, 'windows:', wrecked.windows);
await page.evaluate(() => window.__THREE_GAME_TEST_HOOKS__?.setState('title'));
await page.waitForTimeout(600);
await page.evaluate(() => window.__THREE_GAME_TEST_HOOKS__?.setState('night'));
await page.waitForTimeout(1200);
const restored = await page.evaluate(() => window.__THREE_GAME_TEST_HOOKS__?.meshHouseInfo());
console.log('[restored]', JSON.stringify(restored.houses.map(h => [h.parts, h.collapsed])), 'windows:', restored.windows);
const ok = restored.houses.every(h => !h.collapsed && h.fraction === 0);
console.log(ok && errors.length === 0 ? 'PASS: reset restores houses + windows' : `FAIL errors=${errors.slice(0,3)}`);
await browser.close();
